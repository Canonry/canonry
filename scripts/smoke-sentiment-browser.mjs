async function storedSummary(project, mode, scope = {}) {
  const url = new URL(`api/v1/projects/${project}/sentiment`, base)
  url.search = new URLSearchParams({ mode, queryClass, scope: 'project', runId: `${project}-run`, ...scope }).toString()
  const response = await context.request.get(url.href)
  if (response.status() !== 200) throw new Error(`Stored ${project} summary returned ${response.status()}`)
  return response.json()
}
async function assertScore(summary) {
  const headline = page.getByLabel(`${classLabel} favorable share`, { exact: true })
  if (!(await headline.innerText()).includes(summary.score.favorableDisplay)) throw new Error('Headline differs from the exact API display')
  const query = summary.queries[0]
  if (!query) throw new Error('Synthetic selected class has no query score')
  const opener = page.getByRole('button', { name: `View ${classLabel} sentiment evidence for ${query.queryText}`, exact: true })
  await opener.waitFor({ timeout: 30_000 })
  if (!(await opener.innerText()).includes(query.score.favorableDisplay) || !(await opener.innerText()).includes(`${query.coverage.judged} judged`)) throw new Error('Query score differs from stored API values')
  return opener
}

