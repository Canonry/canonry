const COUNTRY_CRITERIA = new Map(COUNTRIES.map(entry => [2000 + Number(entry.slice(2)), entry.slice(0, 2)]))
const names = new Intl.DisplayNames(['en'], { type: 'region' })
const COUNTRY_NAMES = new Map(COUNTRIES.map(entry => [names.of(entry.slice(0, 2))!.toLowerCase(), entry.slice(0, 2)]))

/** The alpha-2 code of a Google Ads country criterion id, or null when the id is not a country cloro supports. */
export function countryOfCriterion(locationCode: number): string | null {
  return COUNTRY_CRITERIA.get(locationCode) ?? null
}

/** The alpha-2 code of a country by its English name ("United States"), ignoring case, or null. */
export function countryOfName(name: string): string | null {
  return COUNTRY_NAMES.get(name.trim().toLowerCase()) ?? null
}
